# ============================================================
# 场景 1：.R 脚本 —— 逐行送进 R 终端执行
#
# 玩法：光标放在某一行，按 ⌘Enter。第一次按会自动起一个 R 终端。
#      之后每按一次，就把光标所在的那一行送进去跑，光标自动下移。
#      想反复调同一行 → 用 ⌥Enter（跑完光标不动）。
#
# 这个文件从上往下按 ⌘Enter 一路按到底就行。
# ============================================================


# ---- 1. 先确认终端起来了 --------------------------------------------------
# 按 ⌘Enter 跑下面这行。第一次会弹出一个 R 终端，等它加载完。
R.version.string


# ---- 2. 变量会留在 Environment 面板里 -------------------------------------
# 跑完这几行后，看左边活动栏的 R 图标 → Workspace 面板，
# 应该能看到 x / y / cars 三个变量。这就是 RStudio 的 Environment。
x <- 42
y <- c("a", "b", "c")
cars <- mtcars


# ---- 3. Data viewer：点开表格看 -------------------------------------------
# 跑这行，会在编辑器里开一个表格标签页。
# 也可以在 Workspace 面板里直接点 cars 那一行，效果一样。
View(cars)


# ---- 4. tidyverse 管道 ----------------------------------------------------
library(tidyverse)

# |> 是 R 原生管道，把左边的东西喂给右边的函数当第一个参数。
# 523 第一讲就在讲这个。
mtcars |>
  filter(cyl == 4) |>
  select(mpg, wt, hp) |>
  arrange(desc(mpg))

# 上面这一段是跨多行的。⌘Enter 会自动识别完整表达式，
# 光标放在第一行按一次就能把整段跑掉，不用手动选中。


# ---- 5. 画图：应该出现在面板里，不是弹窗 ----------------------------------
# 如果配置生效了（r.plot.useHttpgd），图会画在编辑器的一个面板里。
# 如果弹出了独立窗口，说明设置没生效 —— 重启编辑器。
ggplot(mtcars, aes(x = wt, y = mpg, colour = factor(cyl))) +
  geom_point(size = 3) +
  labs(title = "重量 vs 油耗", x = "重量 (1000 lbs)", y = "每加仑英里数",
       colour = "气缸数") +
  theme_minimal()

# 再画一张，面板里可以用箭头在多张图之间翻。
ggplot(mtcars, aes(x = factor(cyl), y = mpg)) +
  geom_boxplot(fill = "steelblue", alpha = 0.6) +
  theme_minimal()


# ---- 6. 查帮助 ------------------------------------------------------------
# 跑这行，帮助页会开在编辑器里。
?dplyr::filter

# 或者：把光标停在下面这个函数名上，⇧⌘P → "R: Open help for selection"
# summarise


